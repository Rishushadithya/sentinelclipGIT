# ---------------------------------------------------------------------------
# Sidebar — Auth & API status
# ---------------------------------------------------------------------------

with st.sidebar:
    st.markdown("## 🛡️ SentinelClip")
    st.markdown("**Local DLP Dashboard**")
    st.markdown("---")

    # Local API deployments can use the token generated by the API directly.
    # Remote/LAN deployments continue to use the manually entered token.
    api_base_is_configured = bool(os.getenv("SENTINELCLIP_API_BASE"))
    local_token = "" if api_base_is_configured else _load_local_admin_token()
    current_token = local_token or st.session_state.get("token", "")
    if local_token:
        st.session_state["admin_token"] = local_token

    # Admin token input
    admin_token = st.text_input(
        "Admin Token",
        type="password",
        help="Enter the token from config/.admin_token",
        value=current_token,
        key="admin_token",
    )

    # Store token in session
    if local_token:
        st.session_state["token"] = local_token
    elif admin_token:
        st.session_state["token"] = admin_token

    # Initialize API client
    token = st.session_state.get("token", "")
    api = SentinelClipAPI(admin_token=token)

    # API status
    st.markdown("---")
    st.markdown("### API Status")
    try:
        health = api.health()
        if health.get("status") == "ok":
            st.markdown(
                '<span class="status-badge status-online">● Online</span>',
                unsafe_allow_html=True,
            )
            st.caption(f"v{health.get('version', '?')}")
        else:
            st.markdown(
                '<span class="status-badge status-offline">● Offline</span>',
                unsafe_allow_html=True,
            )
    except Exception:
        st.markdown(
            '<span class="status-badge status-offline">● Offline</span>',
            unsafe_allow_html=True,
        )
        st.caption("Start Flask API: `py -m api.app`")

    st.markdown("---")
    if st.button("🔄 Refresh Data"):
        st.rerun()


